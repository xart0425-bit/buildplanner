/**
 * UI translations.
 *
 * One setting drives both the interface language and the language the AI writes in —
 * a user who picks Japanese wants the whole product in Japanese, not a Korean shell
 * around Japanese output. The value lives in localStorage next to the API keys; the
 * `useLanguage` hook re-renders every subscriber the moment it changes, so switching
 * does not need a page reload.
 */
import { useSyncExternalStore } from "react";
import {
  DEFAULT_ANALYSIS_LANGUAGE,
  normalizeLanguage,
  type AnalysisLanguage,
} from "@shared/languages";
import { PAGE_MESSAGES, type PageMessages } from "./i18n-pages";

export const LANGUAGE_STORAGE_KEY = "buildplanner-analysis-language";
const LANGUAGE_CHANGE_EVENT = "buildplanner:language-change";

export function getLanguage(): AnalysisLanguage {
  try {
    return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
  } catch {
    return DEFAULT_ANALYSIS_LANGUAGE;
  }
}

export function setLanguage(language: AnalysisLanguage): void {
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  window.dispatchEvent(new Event(LANGUAGE_CHANGE_EVENT));
}

function subscribe(onChange: () => void): () => void {
  window.addEventListener(LANGUAGE_CHANGE_EVENT, onChange);
  // `storage` fires when another tab changes it.
  window.addEventListener("storage", onChange);
  return () => {
    window.removeEventListener(LANGUAGE_CHANGE_EVENT, onChange);
    window.removeEventListener("storage", onChange);
  };
}

/** Current UI language, kept in sync across components and tabs. */
export function useLanguage(): AnalysisLanguage {
  return useSyncExternalStore(subscribe, getLanguage, () => DEFAULT_ANALYSIS_LANGUAGE);
}

const LOCALES: Record<AnalysisLanguage, string> = {
  en: "en-US",
  ko: "ko-KR",
  ja: "ja-JP",
  zh: "zh-CN",
  fr: "fr-FR",
  ru: "ru-RU",
};

/** BCP-47 locale for date and number formatting, following the UI language. */
export function useLocale(): string {
  return LOCALES[useLanguage()] ?? "en-US";
}

/** The message bundle for the current language, main and page tables merged. */
export function useT(): Messages & PageMessages {
  const language = useLanguage();
  return {
    ...(MESSAGES[language] ?? MESSAGES.en),
    ...(PAGE_MESSAGES[language] ?? PAGE_MESSAGES.en),
  };
}

